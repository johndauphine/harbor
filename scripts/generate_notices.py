#!/usr/bin/env python3
"""Preserve upstream notices for Harbor's compiled runtime dependency graph."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ("darwin/arm64", "windows/arm64", "windows/amd64", "linux/amd64")
DESKTOP_TARGETS = ("windows/arm64", "windows/amd64")
DOCUMENT = re.compile(r"^(LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE|PATENTS|AUTHORS)(?:[._-].*)?$", re.I)


def json_stream(text):
    decoder = json.JSONDecoder()
    while text.strip():
        text = text.lstrip()
        value, end = decoder.raw_decode(text)
        yield value
        text = text[end:]


def notice_documents(root, package_dirs):
    """Include root notices and notices inherited by compiled package folders."""
    directories = {root}
    for directory in package_dirs:
        directory = Path(directory)
        if not directory.is_relative_to(root):
            raise RuntimeError("Dependency package lies outside its reported module")
        while directory != root:
            directories.add(directory)
            directory = directory.parent
    return sorted({path for directory in directories for path in directory.iterdir()
                   if path.is_file() and DOCUMENT.fullmatch(path.name)
                   and path.suffix.lower() not in {".go", ".yml", ".yaml", ".json"}},
                  key=lambda path: path.relative_to(root).as_posix())


def render_notices():
    environment = json.loads(subprocess.check_output(["go", "env", "-json", "GOROOT", "GOVERSION"], cwd=ROOT, text=True, encoding="utf-8"))
    goroot = Path(environment["GOROOT"])
    standard_dirs = set()
    modules = {}
    graphs = [(target, []) for target in TARGETS]
    graphs += [(target, ["-tags", "desktop,production"]) for target in DESKTOP_TARGETS]
    for target, tags in graphs:
        system, arch = target.split("/")
        output = subprocess.check_output(["go", "list", *tags, "-deps", "-json", "."], cwd=ROOT,
                                         env=dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0"), text=True, encoding="utf-8")
        for package in json_stream(output):
            if package.get("Standard"):
                standard_dirs.add(package["Dir"])
                continue
            module = package.get("Module")
            if not module or module.get("Main"):
                continue
            if module.get("Replace"):
                raise RuntimeError("Review local/replaced dependency attribution before packaging")
            key = (module["Path"], module["Version"])
            record = modules.setdefault(key, {"root": Path(module["Dir"]), "directories": set()})
            record["directories"].add(package["Dir"])
    text = [
        "Harbor third-party notices\n",
        "Generated by scripts/generate_notices.py; do not edit upstream text by hand.\n",
        "Scope: runtime imports for " + ", ".join(TARGETS) + " with CGO_ENABLED=0.\n",
        "Includes desktop,production build tags for " + ", ".join(DESKTOP_TARGETS) + ".\n",
        "This combines the supported target graphs; not every listed package is linked on every target.\n",
        "Upstream module-level notices may also describe optional, test-only or build-only components.\n",
        "Those supplied notices are preserved intact, not reclassified as Harbor runtime components.\n",
        "Harbor's own Apache-2.0 license is provided separately in LICENSE.\n\n",
        "Runtime dependency modules:\n",
    ]
    for name, version in sorted(modules):
        text.append(f"  {name} {version}\n")
    text.append(f"  Go toolchain/runtime {environment['GOVERSION']}\n\n")
    sources = [(f"Go toolchain/runtime {environment['GOVERSION']}", goroot, standard_dirs)]
    sources += [(f"{name} {version}", record["root"], record["directories"])
                for (name, version), record in sorted(modules.items())]
    for label, root, directories in sources:
        documents = notice_documents(root, directories)
        if not any(path.name.upper().startswith(("LICENSE", "LICENCE", "COPYING")) for path in documents):
            raise RuntimeError(f"No license text located for {label}; review attribution before packaging")
        for path in documents:
            text.append("=" * 78 + "\n")
            text.append(f"Component: {label}\nUpstream file: {path.relative_to(root).as_posix()}\n")
            text.append("=" * 78 + "\n\n")
            original = path.read_bytes().decode("utf-8")
            text.append(original)
            if not original.endswith("\n"):
                text.append("\n")
            text.append("\n")
    return "".join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in notices differ from current dependency inputs")
    args = parser.parse_args()
    generated = render_notices()
    destination = ROOT / "THIRD_PARTY_NOTICES.txt"
    if args.check:
        if not destination.exists() or destination.read_bytes() != generated.encode("utf-8"):
            raise SystemExit("Third-party notices are stale; run python scripts/generate_notices.py and review/commit the result")
        print("Third-party notices match the current runtime dependencies and toolchain.")
    else:
        destination.write_bytes(generated.encode("utf-8"))
        print(f"Generated {destination.name} ({len(generated.encode('utf-8'))} bytes).")


if __name__ == "__main__":
    main()
